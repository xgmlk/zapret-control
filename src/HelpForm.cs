        internal const string GameFilter =
@"ЧТО ЭТО ТАКОЕ

Zapret — это обход блокировок. Он помогает открывать Discord, YouTube и другие сайты, когда провайдер их замедляет или блокирует.

Иногда обход мешает играм: игра может не подключаться к серверу, не находить матч или лагать. Game Filter — это ограничение: обход работает только с теми портами, которые вы разрешите. Остальной трафик программа не трогает.

ПОРТ — ЧТО ЭТО

Порт — это число, как «дверь», через которую программа общается с сервером. У игры свои порты, обычно это числа больше 1023. Если не знаете порты игры, оставьте диапазон по умолчанию 1024-65535 — он подходит большинству игр.

РЕЖИМЫ

• Выключен — Game Filter не используется. Обход работает как обычно.
• TCP и UDP — обход применяется к указанным TCP- и UDP-портам.
• Только TCP — только к TCP-портам.
• Только UDP — только к UDP-портам.

ЧТО ДЕЛАТЬ

1. Выберите режим. Для игр обычно подходит «TCP и UDP».
2. Проверьте диапазоны. По умолчанию 1024-65535.
3. Нажмите «Сохранить и применить». Служба перезапустится.
4. Запустите игру и проверьте подключение.

ЕСЛИ ИГРА НЕ РАБОТАЕТ

• Верните «Выключен» и нажмите «Сохранить и применить». Если игра заработала — значит, обход ей мешал.
• Если не помогло, проверьте IPSet: вкладка «IPSet» → «Отключён» или «Пустой (any)» → перезапустите службу.
• Если игра работает, но с большим пингом, попробуйте «Только UDP» или «Только TCP» — иногда помогает.

ВАЖНО

• Не вписывайте порт 443: через него работают сайты, Discord и YouTube. Если добавить 443, обход начнёт мешать им.
• Изменения применяются только после перезапуска службы. Кнопка «Сохранить и применить» делает это сама.
• Если стратегия не использует Game Filter, вкладка покажет предупреждение — тогда настройка не попадёт в обход. Выберите другую стратегию или оставьте как есть.";

        internal const string Ipset =
@"ЧТО ЭТО ТАКОЕ

IPSet — это список IP-адресов (цифровых адресов серверов), к которым применяется обход. Список ipset-all.txt приходит от Flowseal и обновляется кнопкой «Обновить список IPSet».

Список нужен, чтобы обход не ломал сайты и сервисы, которым он не нужен. Если сервис плохо работает с обходом, его адрес можно исключить.

РЕЖИМЫ

• «Загружен» — используется список. Обход применяется к адресам из списка. Это обычный режим.
• «Отключён» — список выключен: в файл записывается один служебный адрес 203.0.113.113/32. Правила, которые смотрят на список, не срабатывают.
• «Пустой (any)» — список пустой, и под фильтр попадает любой IP. Это может помочь играм, но может сломать открытие многих сайтов. Не оставляйте этот режим навсегда.

КОГДА МЕНЯТЬ

• Обычно — «Загружен».
• Если сайт или игра не работает, а без zapret работает — попробуйте «Отключён» или «Пустой (any)», перезапустите службу и проверьте.
• Для игр Flowseal советует: обновить IPSet, включить Game Filter, а если не помогло — временно попробовать «Пустой (any)». После проверки верните «Загружен».

ОБНОВЛЕНИЕ СПИСКА

Кнопка «Обновить список IPSet» скачивает свежий список, проверяет формат и сохраняет резервную копию. После обновления перезапустите службу, чтобы обход прочитал новый список.

ВАЖНО

• Переключение режима сохраняет резервную копию.
• Обход читает список при запуске, поэтому нужен перезапуск службы.
• Не редактируйте ipset-all.txt вручную, если не уверены: обновление списка заменит файл.";

        internal const string Fakes =
@"ЧТО ЭТО ТАКОЕ

«Фейк» — это маленький файл с ненастоящим (поддельным) пакетом. Обход отправляет его перед настоящим запросом, чтобы провайдер не смог распознать соединение и не заблокировал его. Для разных сервисов нужны разные фейки.

В программе два активных файла:
• Discord UDP — для голосового чата Discord.
• GameFilter UDP — для игр, когда включён Game Filter.

Активный файл программа определяет по SHA256 — это как отпечаток файла, чтобы точно показать, какой сейчас используется.

ЧТО МОЖНО СДЕЛАТЬ

В списке ниже — все файлы фейков из папки bin. Выберите файл и нажмите:
• «Заменить Discord» — подставить выбранный файл для Discord.
• «Заменить GameFilter» — подставить для игр.

Перед заменой программа делает резервную копию. После замены перезапустите службу, чтобы обход прочитал новый файл.

КОГДА МЕНЯТЬ

• Если не работает голосовой чат Discord — попробуйте другой файл для Discord.
• Если не работает игра с включённым Game Filter — попробуйте другой файл для GameFilter.
• Меняйте по одному и проверяйте результат. Не меняйте оба сразу — иначе непонятно, что помогло.

ВАЖНО

• Не все стратегии используют эти файлы. Если стратегия не ссылается на ACTIVE_DISCORD_UDP.bin или ACTIVE_GAME_UDP.bin, замена может не повлиять.
• Замена не устанавливает и не удаляет драйверы и не меняет список сайтов.
• Если сомневаетесь — верните файл из резервной копии, путь к которой покажет программа после замены.";

    // Scrollable plain-language help used by the Game Filter, IPSet and Fakes
    // tabs. The text avoids jargon and explains the practical consequences.
    public sealed class HelpForm : Form
    {
        public HelpForm(string title, string text)
        {
            Text = title;
            ClientSize = new Size(700, 620);
            FormBorderStyle = FormBorderStyle.FixedDialog;
            MaximizeBox = false;
            MinimizeBox = false;
            StartPosition = FormStartPosition.CenterParent;
            ShowInTaskbar = false;
            BackColor = Color.FromArgb(247, 246, 243);
            ForeColor = Color.FromArgb(44, 44, 46);
            Font = new Font("Segoe UI", 9F);
            AutoScaleMode = AutoScaleMode.Dpi;

            using (System.IO.Stream iconStream = typeof(HelpForm).Assembly
                .GetManifestResourceStream("ZapretControl.app.ico"))
            {
                if (iconStream != null)
                {
                    Icon = new Icon(iconStream, new Size(64, 64));
                }
            }

            Label header = new Label();
            header.Text = title;
            header.Font = new Font("Segoe UI", 12F, FontStyle.Bold);
            header.SetBounds(20, 16, 660, 26);
            Controls.Add(header);

            Label subtitle = new Label();
            subtitle.Text = "Простыми словами — без технических терминов.";
            subtitle.ForeColor = Color.FromArgb(110, 110, 115);
            subtitle.Font = new Font("Segoe UI", 8.5F);
            subtitle.SetBounds(20, 44, 660, 18);
            Controls.Add(subtitle);

            RichTextBox body = new RichTextBox();
            body.SetBounds(20, 68, 660, 486);
            body.ReadOnly = true;
            body.BorderStyle = BorderStyle.FixedSingle;
            body.BackColor = Color.FromArgb(252, 251, 248);
            body.ForeColor = Color.FromArgb(44, 44, 46);
            body.Font = new Font("Segoe UI", 9.5F);
            body.DetectUrls = false;
            body.WordWrap = true;
            body.ScrollBars = RichTextBoxScrollBars.Vertical;
            body.Text = text ?? string.Empty;
            Controls.Add(body);

            Button close = new Button();
            close.Text = "Понятно";
            close.SetBounds(560, 566, 120, 32);
            close.Click += delegate { Close(); };
            Controls.Add(close);

            AcceptButton = close;
            CancelButton = close;
        }
    }

    internal static class HelpTexts
